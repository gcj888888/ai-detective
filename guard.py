"""输入边界检查：按赛事规则，本作品不碰时政和涉及个人的消息。

官方规则原文（https://1024.waytoagi.com/tracks/detective）：
  "围绕「少点幻觉，多点搜索」，用元宝搜索做一个会查的 AI 作品……
   核心是搜索：去掉元宝搜索，作品就转不起来。**不碰时政和涉及个人的消息。**"

做法：命中明确的时政 / 个人隐私领域词或个人私事指控时，直接返回友好提示，
不调用搜索、也不调用大模型（顺带省额度）。

规则保持小而可解释；它不能识别人名或覆盖所有表达变体，不能据此声称完全合规。
"""

import re

# 时政与政治实体
_TOPIC_POLITICS = [
    "习近平", "毛泽东", "毛主席", "邓小平", "周恩来", "刘少奇", "林彪", "蒋介石",
    "普京", "特朗普", "拜登", "泽连斯基", "莫迪", "内塔尼亚胡", "安倍", "金正恩",
    "国家主席", "国家总理", "总统", "首相", "总书记", "主席台",
    "大选", "总统大选", "选举", "公投", "政变", "内阁", "弹劾", "组阁",
    "共产党", "国民党", "民进党", "民主党", "共和党", "自民党", "工党",
    "台独", "港独", "疆独", "藏独", "法轮功", "六四", "天安门事件", "反送中",
    "俄乌", "巴以", "加沙", "北约", "联合国制裁", "宣战", "停战协议",
]

# 个人隐私与可识别信息
_TOPIC_PRIVACY = [
    "身份证号", "身份证号码", "电话号码", "手机号码", "家庭住址", "家庭地址",
    "开房记录", "通话记录", "户籍信息", "人肉搜索", "个人信息泄露", "隐私泄露",
    "简历", "工资单", "工资条", "病历", "体检报告", "银行账号", "银行卡号",
    "密码泄露", "聊天记录",
]

_TOPICS = _TOPIC_POLITICS + _TOPIC_PRIVACY

# 只放行不含具体对象、号码或记录查询的格式/防护常识问法。
_GENERIC_PRIVACY_KNOWLEDGE = [
    "身份证号码有18位是真的吗", "身份证号有18位是真的吗",
    "身份证号码是18位吗", "身份证号是18位吗",
    "身份证号码长度", "身份证号长度", "身份证有几位",
    "手机验证码怎么防护", "手机验证码如何防护",
    "如何保护手机验证码", "怎样保护手机验证码",
]

# 有明确私事/不当行为且附近出现个人姓名、称谓时拦截。
_PERSONAL_CLAIM = re.compile(
    r"(?:[\u4e00-\u9fff]{2,4})(?:.{0,4})(?:有婚外情|婚外情|出轨|劈腿|挪用(?:班费|公款|资金)|贪污|受贿|偷窃|盗窃|家暴|吸毒|嫖娼)"
)

NOTICE = (
    "按赛事规则，这个工具不碰时政和涉及个人的消息，所以这条没有去查。"
    "换个健康、生活、消费类的传闻试试——比如「隔夜开水能不能喝」。"
)


def check_query(query: str):
    """命中边界返回提示文案；未命中返回 None。"""
    if not query:
        return None
    q = query.lower()
    # 必须整句匹配，不能让“格式常识 + 查询某人号码”绕过边界。
    if q.strip().rstrip("？?。！!") in _GENERIC_PRIVACY_KNOWLEDGE:
        return None
    for w in _TOPICS:
        if w.lower() in q:
            return NOTICE
    if _PERSONAL_CLAIM.search(query):
        return NOTICE
    return None
